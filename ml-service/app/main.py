"""
app/main.py
-----------
The ML microservice.

Run locally:
    uvicorn app.main:app --reload --port 8001

Endpoints
    GET  /health          liveness + which artifacts are loaded
    POST /v1/analyze      multipart upload + vitals -> full analysis
    POST /v1/extract      OCR only, no models (useful for debugging regexes)

Security posture
----------------
This service is *internal*. It sits behind the Node.js API and is never exposed
to the browser, because it does no user authentication. A shared secret header
(`X-Service-Token`) enforces that only the Node backend can reach it, and CORS
is closed. In the report, state clearly that patient identity is handled in
Node and this service only ever sees de-identified clinical values.
"""

from __future__ import annotations

import json
import logging
import os
import time
from contextlib import asynccontextmanager

from fastapi import Depends, FastAPI, File, Form, Header, HTTPException, UploadFile, status
from fastapi.middleware.cors import CORSMiddleware
from pydantic import ValidationError

from app import inference, ocr
from app.schemas import AnalysisResponse, BiomarkerReading, Vitals
from core.biomarkers import BIOMARKERS

logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(name)s: %(message)s")
log = logging.getLogger("ml-service")
SERVICE_TOKEN = os.getenv("ML_SERVICE_TOKEN", "change-me-in-.env")
MAX_UPLOAD_BYTES = 10 * 1024 * 1024  # 10 MB
ALLOWED_TYPES = {"image/png", "image/jpeg", "image/jpg", "image/webp",
                 "image/tiff", "image/bmp", "application/pdf"}

DISCLAIMER = (
    "Generated by an academic machine-learning prototype. Not a medical device "
    "and not a diagnosis. Every output must be reviewed by a registered medical "
    "practitioner before any clinical or medication decision."
)


@asynccontextmanager
async def lifespan(_: FastAPI):
    """Load the .pkl artifacts once, at startup, so the first request is not slow."""
    inference.load_models()
    log.info("ML service ready")
    yield
    log.info("ML service shutting down")


app = FastAPI(
    title="Clinical Extraction & Predictive Healthcare ML Service",
    version="1.0.0",
    description="OCR + Random Forest + XGBoost + content-based diet filtering.",
    lifespan=lifespan,
)

# Only the Node backend talks to this service, so no browser origins are allowed.
app.add_middleware(
    CORSMiddleware,
    allow_origins=[],
    allow_methods=["POST", "GET"],
    allow_headers=["*"],
)


def verify_service_token(x_service_token: str = Header(default="")) -> None:
    """Reject anything that is not the Node backend."""
    if x_service_token != SERVICE_TOKEN:
        raise HTTPException(status.HTTP_401_UNAUTHORIZED, "Invalid service token")


async def read_upload(file: UploadFile) -> bytes:
    if file.content_type not in ALLOWED_TYPES:
        raise HTTPException(
            status.HTTP_415_UNSUPPORTED_MEDIA_TYPE,
            f"Unsupported file type {file.content_type}. Upload a PNG, JPEG or PDF.",
        )
    content = await file.read()
    if not content:
        raise HTTPException(status.HTTP_400_BAD_REQUEST, "The uploaded file is empty.")
    if len(content) > MAX_UPLOAD_BYTES:
        raise HTTPException(
            status.HTTP_413_REQUEST_ENTITY_TOO_LARGE,
            f"File exceeds {MAX_UPLOAD_BYTES // (1024 * 1024)} MB.",
        )
    return content


@app.get("/health")
def health() -> dict:
    try:
        reg = inference.registry()
        return {
            "status": "ok",
            "disease_classes": len(reg.disease_contract.classes),
            "drug_classes": len(reg.drug_contract.classes),
            "dishes_indexed": int(reg.diet_engine["matrix"].shape[0]),
        }
    except RuntimeError as exc:
        raise HTTPException(status.HTTP_503_SERVICE_UNAVAILABLE, str(exc))


@app.post("/v1/extract", dependencies=[Depends(verify_service_token)])
async def extract_only(file: UploadFile = File(...)) -> dict:
    """OCR without prediction. Use this to iterate on the regex patterns."""
    content = await read_upload(file)
    result = ocr.extract(content, file.content_type)
    return {
        "ocr_confidence": result.ocr_confidence,
        "values": result.values,
        "statuses": result.statuses,
        "suspect": result.suspect,
        "raw_text": result.raw_text[:5000],
    }


@app.post("/v1/analyze", response_model=AnalysisResponse,
          dependencies=[Depends(verify_service_token)])
async def analyze(
    file: UploadFile = File(..., description="Lab report image or PDF"),
    vitals: str = Form(..., description="JSON-encoded Vitals object"),
) -> AnalysisResponse:
    """
    The main endpoint. Node.js posts the report plus the patient's vitals and
    gets back everything the dashboard needs in one response.

    Vitals arrive as a JSON *string* because the request is multipart/form-data,
    which has no native nested-object encoding.
    """
    started = time.perf_counter()
    warnings: list[str] = []

    try:
        parsed_vitals = Vitals(**json.loads(vitals)).with_derived_bmi()
    except (json.JSONDecodeError, ValidationError) as exc:
        raise HTTPException(status.HTTP_422_UNPROCESSABLE_ENTITY, f"Invalid vitals: {exc}")

    content = await read_upload(file)

    # ---- Stage 1: OCR -----------------------------------------------------
    try:
        extraction = ocr.extract(content, file.content_type)
    except Exception as exc:  # noqa: BLE001 - surface a clean 422, log the trace
        log.exception("OCR failed")
        raise HTTPException(status.HTTP_422_UNPROCESSABLE_ENTITY,
                            f"Could not read the report: {exc}")

    if not extraction.values:
        raise HTTPException(
            status.HTTP_422_UNPROCESSABLE_ENTITY,
            "No recognisable biomarkers were found. Upload a clearer, well-lit "
            "photo of the results table, or a PDF from the lab.",
        )
    if extraction.ocr_confidence < 60:
        warnings.append(
            f"OCR confidence is low ({extraction.ocr_confidence}%). Check the "
            "extracted values against the report before trusting the result."
        )
    for name in extraction.suspect:
        warnings.append(f"{name} was read as an implausible value and is likely an OCR error.")

    # ---- Stages 2-4: the three models ------------------------------------
    result = inference.run_pipeline(extraction.values, parsed_vitals.model_dump())

    if result["diagnosis"]["inconclusive"]:
        warnings.append(
            "Model confidence is below the reporting threshold. Treat this as a "
            "prompt to investigate, not as a finding."
        )

    biomarkers = [
        BiomarkerReading(
            name=name,
            value=value,
            unit=BIOMARKERS[name].unit,
            status=extraction.statuses[name],
            reference_range=f"{BIOMARKERS[name].low}-{BIOMARKERS[name].high}",
            suspect=name in extraction.suspect,
        )
        for name, value in extraction.values.items()
    ]

    return AnalysisResponse(
        ocr_confidence=extraction.ocr_confidence,
        biomarkers=biomarkers,
        diagnosis=result["diagnosis"],
        medication=result["medication"],
        diet=result["diet"],
        warnings=warnings,
        processing_ms=int((time.perf_counter() - started) * 1000),
        model_versions={
            "disease": inference.registry().disease_contract.model_name,
            "drug": inference.registry().drug_contract.model_name,
            "diet": "tfidf_content_based_v1",
        },
        disclaimer=DISCLAIMER,
    )