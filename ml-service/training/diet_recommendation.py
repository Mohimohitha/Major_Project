import pandas as pd
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.metrics.pairwise import cosine_similarity
import joblib

# 1. Load the Dataset
print("Loading Personalized Medical Diet dataset...")
df_diet = pd.read_csv('Personalized_Diet_Recommendations.csv')

# 2. Preprocess and Clean
print("Cleaning data...")
# Using the exact columns from your printout
cols_to_clean = ['Chronic_Disease', 'Allergies', 'Dietary_Habits', 'Preferred_Cuisine', 'Food_Aversions', 'Recommended_Meal_Plan', 'Exercise_Frequency']

for col in cols_to_clean:
    if col in df_diet.columns:
        # Convert everything to string and handle NaN values
        df_diet[col] = df_diet[col].fillna('').astype(str)

# 3. Create the "Hybrid Profile" for TF-IDF
print("Building Hybrid Patient Profiles...")
# We combine the disease, allergies, and user tastes into one rich string
df_diet['Hybrid_Profile'] = df_diet['Chronic_Disease'] + " " + df_diet['Allergies'] + " " + df_diet['Dietary_Habits'] + " " + df_diet['Preferred_Cuisine'] + " " + df_diet['Food_Aversions']

# 4. TF-IDF Vectorization
print("Vectorizing profiles using TF-IDF...")
tfidf_vectorizer = TfidfVectorizer(stop_words='english')
tfidf_matrix = tfidf_vectorizer.fit_transform(df_diet['Hybrid_Profile'])

# 5. Build the Recommendation Engine (Cosine Similarity)
print("Training the Recommender Engine...")

def get_hybrid_diet_recommendation(disease, preferences):
    # Create a profile for the incoming patient
    patient_profile = f"{disease} {preferences}"

    # Vectorize the new patient's profile
    patient_vector = tfidf_vectorizer.transform([patient_profile])

    # Calculate similarity
    similarity_scores = cosine_similarity(patient_vector, tfidf_matrix)

    # Find the best match
    best_match_idx = similarity_scores.argmax()

    # Return the personalized plan
    recommendation = {
        "Target_Disease": disease,
        "Considered_Preferences": preferences,
        "Recommended_Diet": df_diet.iloc[best_match_idx]['Recommended_Meal_Plan'],
        "Lifestyle_Advice": df_diet.iloc[best_match_idx]['Exercise_Frequency']
    }
    return recommendation

# --- Test the Engine! ---
print("\n--- Testing Hybrid Recommender ---")
test_disease = "Diabetes"
test_preference = "Vegan, Gluten-Free, Low Sugar"
result = get_hybrid_diet_recommendation(test_disease, test_preference)

print(f"Disease: {result['Target_Disease']}")
print(f"Preferences: {result['Considered_Preferences']}")
print(f"Diet Plan: {result['Recommended_Diet']}")
print(f"Lifestyle: {result['Lifestyle_Advice']}")

# 6. Export the Models for your FastAPI Backend
print("\nExporting Dietary Engine...")
joblib.dump(tfidf_vectorizer, 'diet_tfidf_vectorizer.pkl')
df_diet.to_pickle('diet_dataframe.pkl')

print("Success! 'diet_tfidf_vectorizer.pkl' and 'diet_dataframe.pkl' are saved.")